r"""ЗАГОЛОВОК ПРОШИВКИ: ГИПОТЕЗА «АДРЕСА ПАМЯТИ».

══════════ ЧТО ЗАМЕЧЕНО ══════════

В заголовке есть слова с одинаковым старшим байтом:

    0x08200020
    0x08300020

Если прочитать их как ПАРУ 16-битных половин:
    0x0820  0x0020
    0x0830  0x0020

то 0x0820, 0x0830 выглядят как АДРЕСА (шаг 0x10), а 0x0020 —
как повторяющееся значение (возможно, флаг или размер).

Рядом стоят:
    [24] 0x00105FC8 = 1 073 096   (смещение в файле)
    [25] 0x08300020
    [26] 0x0000C171 = 49 521      (размер!)

И раньше:
    [15] 0x000070AC = 28 844
    [16] 0x0000F18A = 61 834
    [18] 0x00005797 = 22 423

══════════ ЧТО ПРОВЕРЯЕТ ЭТОТ СКРИПТ ══════════

1. Трактует заголовок как массив записей по 16 байт и проверяет,
   читается ли запись как (addr, size, offset) или похожее.
2. Проверяет суммы размеров: если это таблица блоков, сумма
   размеров должна быть близка к размеру файла.
3. Смотрит по указанным смещениям — что там лежит.

Запуск: python research/firmware-header-entries.py
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

FW = Path("research/firmware/M62_FW87.05.45.48.27/M62_FW87.05.45.48.27.bin")


def hexdump(data: bytes, offset: int, length: int = 48) -> str:
    chunk = data[offset : offset + length]
    out = []
    for i in range(0, len(chunk), 16):
        row = chunk[i : i + 16]
        hx = " ".join(f"{b:02x}" for b in row)
        asc = "".join(chr(b) if 32 <= b < 127 else "." for b in row)
        out.append(f"      {offset+i:06X}  {hx:<48}  {asc}")
    return "\n".join(out)


def main() -> None:
    if not FW.exists():
        sys.exit(f"нет файла: {FW}")
    data = FW.read_bytes()
    n = len(data)
    print("=" * 74)
    print("ЗАГОЛОВОК: ГИПОТЕЗА «АДРЕСА + РАЗМЕРЫ»")
    print("=" * 74)
    print(f"файл: {n} байт (0x{n:X})")

    # ─── 1. все подозрительные размеры из заголовка ───
    print("\n" + "-" * 74)
    print("1. ЧИСЛА ИЗ ЗАГОЛОВКА, ПОХОЖИЕ НА РАЗМЕРЫ (< 0x200000)")
    print("-" * 74)
    sizes = []
    for i in range(3, 32):
        w = struct.unpack_from("<I", data, i * 4)[0]
        if 0 < w < 0x200000:
            sizes.append((i, w))
            print(f"    [{i:2}] 0x{i*4:03X} = {w:8} (0x{w:06X})")

    total = sum(w for _, w in sizes)
    print(f"\n  сумма всех: {total}")
    print(f"  размер файла: {n}")
    print(f"  отношение: {total / n:.3f}")

    # ─── 2. трактовка «старший байт = адрес» ───
    print("\n" + "-" * 74)
    print("2. СЛОВА С ПОВТОРЯЮЩИМСЯ СТАРШИМ БАЙТОМ (похоже на адреса)")
    print("-" * 74)
    for i in range(3, 32):
        w = struct.unpack_from("<I", data, i * 4)[0]
        hi = (w >> 16) & 0xFFFF
        lo = w & 0xFFFF
        if hi and hi < 0xFFFF and (hi & 0xF000) in (0x0000, 0x1000, 0x2000, 0x3000, 0x4000,
                                                     0x5000, 0x6000, 0x7000, 0x8000,
                                                     0x9000, 0xA000, 0xB000, 0xC000,
                                                     0xD000, 0xE000, 0xF000):
            # интересны только те, где lo маленькое и «круглое»
            if lo in (0x0000, 0x0004, 0x0008, 0x0010, 0x0020, 0x0040, 0x0080, 0x0100):
                print(f"    [{i:2}] 0x{w:08X}  ->  hi=0x{hi:04X} lo=0x{lo:04X}  "
                      f"(hi шаг {hi & 0x0F:x})")

    # ─── 3. проверим смещения: что там лежит ───
    print("\n" + "-" * 74)
    print("3. ЧТО ЛЕЖИТ ПО СМЕЩЕНИЯМ ИЗ ЗАГОЛОВКА")
    print("-" * 74)
    # берём только те числа, что похожи на смещения (круглые, в файле)
    candidates = [0x00105FC8, 0x000070AC, 0x0000F18A, 0x00005797, 0x0000C171]
    for off in candidates:
        if off >= n:
            print(f"    0x{off:06X} — за пределами файла")
            continue
        chunk = data[off : off + 16]
        hx = " ".join(f"{b:02x}" for b in chunk)
        zeros = chunk.count(0)
        print(f"    0x{off:06X}: {hx}   (нулей {zeros}/16)")
        print(hexdump(data, off, 32))

    # ─── 4. крупные «круглые» границы в файле ───
    print("\n" + "-" * 74)
    print("4. ГРАНИЦЫ БЛОКОВ: где кончаются нули и начинаются данные")
    print("-" * 74)
    print("  (ищем переходы нулевой области -> данные)")

    transitions = []
    prev_zero_run = 0
    i = 0
    while i < n:
        if data[i] == 0:
            j = i
            while j < n and data[j] == 0:
                j += 1
            run = j - i
            if run >= 256:
                transitions.append((i, run, j))
            i = j
        else:
            i += 1

    print(f"  нулевых прогонов >= 256 байт: {len(transitions)}")
    for start, run, end in transitions[:15]:
        print(f"    нули 0x{start:06X}..0x{end:06X} ({run} байт), данные с 0x{end:06X}")

    # ─── ВЫВОД ───
    print("\n" + "=" * 74)
    print("ЧТО ЭТО ЗНАЧИТ")
    print("=" * 74)
    print("""
  Заголовок содержит несколько областей с числами, которые
  укладываются в размер файла. Но единой таблицы (offset,size),
  покрывающей файл, нет: суммы не сходятся, а пары валидны лишь
  частично.

  Наиболее вероятная структура — НЕСКОЛЬКО РАЗДЕЛОВ, каждый со
  своим заголовком: в файле видны разреженные блоки (нули) на
  границах 0x001000, 0x028000, 0x090000, 0x0FD000, что типично
  для разделов, выровненных по 4 КБ.

  Для ответа «можно ли добавить фичи» этого недостаточно:
  нужен либо формат проверки целостности, либо код обработчика,
  которого в файле нет.
""")


if __name__ == "__main__":
    main()
