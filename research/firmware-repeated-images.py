r"""ПОВТОРЯЮЩИЕСЯ СТРУКТУРЫ В ПРОШИВКЕ: ШАГ 0x68000.

══════════ ЧТО ЗАМЕЧЕНО ══════════

Нулевые прогоны идут ПАРАМИ с одинаковым паттерном:

    нули 0x000E98..0x00193C (2724 байт), данные с 0x00193C
    нули 0x001952..0x001EB1 (1375 байт), данные с 0x001EB1

    нули 0x027E98..0x02893C (2724 байт), данные с 0x02893C
    нули 0x028952..0x028EB1 (1375 байт), данные с 0x028EB1

    нули 0x08FE98..0x09093C (2724 байт), данные с 0x09093C
    нули 0x090952..0x090EB1 (1375 байт), данные с 0x090EB1

    нули 0x0FCE98..0x0FD93C (2724 байт), данные с 0x0FD93C
    нули 0x0FD952..0x0FDEB1 (1375 байт), данные с 0x0FDEB1

Одинаковые РАЗМЕРЫ прогонов (2724 и 1375) в разных местах —
это не случайность. Значит файл содержит несколько ОДИНАКОВЫХ
по структуре образов.

Расстояния между группами:
    0x00193C -> 0x02893C  = 0x27000
    0x02893C -> 0x09093C  = 0x68000
    0x09093C -> 0x0FD93C  = 0x6D000

══════════ ЧТО ПРОВЕРЯЕТ ЭТОТ СКРИПТ ══════════

1. Сравнивает содержимое этих участков байт в байт — одинаковы ли.
2. Ищет ВСЕ пары (2724, 1375) с одинаковым смещением внутри группы.
3. Если образы совпадают — определяет размер и количество.
4. Смотрит, есть ли в каждом образе свой заголовок.

Запуск: python research/firmware-repeated-images.py
"""

from __future__ import annotations

import hashlib
import struct
import sys
from pathlib import Path

FW = Path("research/firmware/M62_FW87.05.45.48.27/M62_FW87.05.45.48.27.bin")

# границы найденные ранее: (конец нулей 1, конец нулей 2) -> данные с
GROUPS = [
    (0x00193C, 0x001EB1),
    (0x02893C, 0x028EB1),
    (0x09093C, 0x090EB1),
    (0x0FD93C, 0x0FDEB1),
]


def main() -> None:
    if not FW.exists():
        sys.exit(f"нет файла: {FW}")
    data = FW.read_bytes()
    n = len(data)
    print("=" * 74)
    print("ПОВТОРЯЮЩИЕСЯ ОБРАЗЫ В ПРОШИВКЕ")
    print("=" * 74)
    print(f"файл: {n} байт (0x{n:X})")

    print("\n" + "-" * 74)
    print("1. ГРУППЫ НУЛЕЙ (начало данных после них)")
    print("-" * 74)
    for i, (a, b) in enumerate(GROUPS):
        print(f"  группа {i}: данные с 0x{a:06X} и 0x{b:06X}  (разница 0x{b-a:X})")

    print("\n  расстояния между группами:")
    for i in range(len(GROUPS) - 1):
        d1 = GROUPS[i + 1][0] - GROUPS[i][0]
        d2 = GROUPS[i + 1][1] - GROUPS[i][1]
        print(f"    {i}->{i+1}: 0x{d1:06X} ({d1})   и по второму: 0x{d2:06X}")

    # ─── 2. сравнение содержимого после границ ───
    print("\n" + "-" * 74)
    print("2. СРАВНЕНИЕ СОДЕРЖИМОГО ПОСЛЕ ГРАНИЦ (первые 256 байт)")
    print("-" * 74)
    for i, (a, b) in enumerate(GROUPS):
        chunk_a = data[a : a + 256]
        chunk_b = data[b : b + 256]
        same = sum(1 for x, y in zip(chunk_a, chunk_b) if x == y)
        print(f"  группа {i}: 0x{a:06X} vs 0x{b:06X}: совпало {same}/256 байт")
        print(f"    0x{a:06X}: {chunk_a[:24].hex(' ')}")
        print(f"    0x{b:06X}: {chunk_b[:24].hex(' ')}")

    # ─── 3. сравнение групп между собой ───
    print("\n" + "-" * 74)
    print("3. СРАВНЕНИЕ ГРУПП МЕЖДУ СОБОЙ (участок 4 КБ после границы)")
    print("-" * 74)
    for i in range(len(GROUPS)):
        for j in range(i + 1, len(GROUPS)):
            a = GROUPS[i][0]
            b = GROUPS[j][0]
            ca = data[a : a + 4096]
            cb = data[b : b + 4096]
            same = sum(1 for x, y in zip(ca, cb) if x == y)
            pct = same / 4096 * 100
            mark = " <-- ОДИНАКОВО" if pct > 95 else ""
            print(f"  группа {i} vs {j}: {pct:5.1f}% совпадения{mark}")

    # ─── 4. ищем ВСЕ такие пары по всему файлу ───
    print("\n" + "-" * 74)
    print("4. ВСЕ ПАРЫ (2724, 1375) ПО ВСЕМУ ФАЙЛУ")
    print("-" * 74)
    found = []
    i = 0
    while i < n:
        if data[i] != 0:
            i += 1
            continue
        j = i
        while j < n and data[j] == 0:
            j += 1
        run = j - i
        if run in (2724, 1375, 2724 - 0):
            found.append((i, run, j))
        i = max(j, i + 1)

    print(f"  найдено прогонов нужных длин: {len(found)}")
    for start, run, end in found:
        print(f"    нули 0x{start:06X}..0x{end:06X} ({run}), данные с 0x{end:06X}")

    # ─── 5. ищем заголовок в начале каждого образа ───
    print("\n" + "-" * 74)
    print("5. ЧТО В НАЧАЛЕ КАЖДОГО ОБРАЗА (32 байта как слова)")
    print("-" * 74)
    for i, (a, b) in enumerate(GROUPS):
        for label, off in (("A", a), ("B", b)):
            if off + 32 > n:
                continue
            words = struct.unpack_from("<8I", data, off)
            ws = "  ".join(f"0x{w:08X}" for w in words)
            print(f"  группа {i}{label} @0x{off:06X}: {ws}")

    # ─── ВЫВОД ───
    print("\n" + "=" * 74)
    print("ВЫВОД")
    print("=" * 74)
    print("""
  Повторяющиеся размеры нулевых прогонов (2724 и 1375 байт) в разных
  местах файла означают, что структура ОДНОТИПНА: файл состоит из
  нескольких блоков одинаковой раскладки.

  Это важно для вопроса о модификации: если образы однотипны,
  формат понятен в общих чертах. Но по-прежнему НЕ известны:
    • формат проверки целостности (без него запись = кирпич);
    • где именно лежат параметры DSP.
""")


if __name__ == "__main__":
    main()
