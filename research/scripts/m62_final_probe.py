print("\n[3] счётчики 'возвратов' и 'вызовов' в CODE-регионах")
CODE = [(0x4b000,0x62000),(0x64000,0x6a000),(0x6b000,0x78000),
        (0xb5000,0xcd000),(0xce000,0xd4000),(0xd5000,0xe2000)]
cb = b"".join(d[a:z] for a, z in CODE)
print("   размер CODE-выборки:", len(cb))
ret_pats = {
    "x86 ret C3":            b"\xc3",
    "x86 leave C9":          b"\xc9",
    "ARM bx lr 1E FF 2F E1": b"\x1e\xff\x2f\xe1",
    "Thumb bx lr 70 47":     b"\x70\x47",
    "MIPS jr ra 08 00 e0 03":b"\x08\x00\xe0\x03",
    "RISC-V ret 67 80 00 00":b"\x67\x80\x00\x00",
}
for k, pat in ret_pats.items():
    print("   %-26s %6d  (%.3f на 100 байт)" % (k, cb.count(pat), 100*cb.count(pat)/len(cb)))

# -------------------------------------------------------------
# 4. Проверка на «микрокод DSP»: инструкции фиксированной длины 32/48/64 бит
#    Для DSP-ядер характерны: очень мало уникальных опкодов, но много данных
# -------------------------------------------------------------
print("\n[4] проверка фиксированной длины инструкции")
for L in [2, 4, 8, 16]:
    words = [cb[i:i+L] for i in range(0, len(cb)-L, L)]
    c = collections.Counter(words)
    top = c.most_common(3)
    tot = sum(c.values())
    print("   длина %2d Б : уникальных %6d (%.1f%%),  top: %s" % (
        L, len(c), 100*len(c)/tot, " ".join("%s:%.2f%%" % (k.hex(), 100*v/tot) for k, v in top)))

