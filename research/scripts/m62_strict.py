def x86_len_probe(buf, limit=200000):
    """Очень грубая проверка: считаем долю позиций, где байт — типичный
    пролог/эпилог/частый опкод."""
    common = set([0x55,0x53,0x56,0x57,0x48,0x89,0x8B,0xE8,0xC3,0x0F,0x83,0x74,0x75,0xEB,0xB8,0x33,0x31,0x41,0x4C])
    n = min(len(buf), limit)
    return sum(1 for b in buf[:n] if b in common) / n

